"""
Opt-in end-to-end voice test against the REAL local Whisper model.

Run with:  RUN_VOICE_E2E=1 python -m unittest discover -s test/unit -p "test_voice_e2e*.py"
(downloads the Whisper model on first run, hence opt-in). The fixtures are Spanish dictations
synthesized with a Windows SAPI voice, resampled to 16 kHz mono.
"""

import asyncio
import os
import unittest
import wave
from pathlib import Path

from src.core.config import settings
from src.services.transcription import normalize_spoken_uml, transcribe_audio_bytes

FIXTURES = Path(__file__).resolve().parent.parent / "fixtures" / "audio"


def _wav_silence(seconds: float = 2.0) -> bytes:
    import io

    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(16000)
        wav.writeframes(b"\x00\x00" * int(16000 * seconds))
    return buffer.getvalue()


@unittest.skipUnless(os.getenv("RUN_VOICE_E2E") == "1", "set RUN_VOICE_E2E=1 to run real-Whisper tests")
class TestRealWhisperDictation(unittest.TestCase):
    def setUp(self):
        self._engine = settings.WHISPER_ENGINE
        settings.WHISPER_ENGINE = "local"

    def tearDown(self):
        settings.WHISPER_ENGINE = self._engine

    def _transcribe(self, name):
        data = (FIXTURES / name).read_bytes()
        return asyncio.run(transcribe_audio_bytes(data, name))

    def test_relationship_dictation_is_understood(self):
        text, confidence = self._transcribe("relation_es.wav")
        normalized = normalize_spoken_uml(text).lower()
        self.assertGreater(confidence, 0.5)
        self.assertIn("composición", normalized)
        self.assertIn("pedido", normalized)
        self.assertIn("1 a *", normalized)

    def test_attribute_dictation_becomes_uml_notation(self):
        text, confidence = self._transcribe("attributes_es.wav")
        normalized = normalize_spoken_uml(text).lower()
        self.assertGreater(confidence, 0.5)
        self.assertIn("clase cliente", normalized)
        self.assertIn("nombre: string", normalized)
        self.assertIn("edad: int", normalized)

    def test_browser_webm_opus_recording_is_transcribed(self):
        # Chrome/Firefox MediaRecorder output (generated by make_audio_fixtures.py).
        text, confidence = self._transcribe("relation_es.webm")
        self.assertTrue(text.strip())
        self.assertIn("pedido", normalize_spoken_uml(text).lower())
        self.assertGreater(confidence, 0.3)

    def test_safari_m4a_recording_is_transcribed(self):
        text, confidence = self._transcribe("relation_es.m4a")
        self.assertTrue(text.strip())
        self.assertIn("pedido", normalize_spoken_uml(text).lower())
        self.assertGreater(confidence, 0.3)

    def test_silence_yields_no_text(self):
        text, confidence = asyncio.run(transcribe_audio_bytes(_wav_silence(), "silence.wav"))
        self.assertEqual((text, confidence), ("", 0.0))


if __name__ == "__main__":
    unittest.main()
